std::vector<Math::Triangle> Math::clipAgainstPlaneMinMaxZ(const Math::Triangle& triangle)
{
    std::vector<Math::Triangle> traingles_clipped_min_z = Math::clipAgainstPlaneMinZ(triangle);

    std::vector<Math::Triangle> traingles_clipped_min_max_z;
    traingles_clipped_min_max_z.reserve(4); // 2 triangles can become 4.

    for(const Math::Triangle& traingle_clipped_min_z : traingles_clipped_min_z)
    {
        std::vector<Math::Triangle> clipped = Math::clipAgainstPlaneMaxZ(traingle_clipped_min_z);
        traingles_clipped_min_max_z.insert(traingles_clipped_min_max_z.end(), clipped.begin(), clipped.end());
    }

    return traingles_clipped_min_max_z;
}
