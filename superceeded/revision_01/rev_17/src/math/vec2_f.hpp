namespace Math
{
    struct Vec2_f
    {
        //-----------------------------------------------------------------------------------------------------------------//
        float m_data[2];
        //-----------------------------------------------------------------------------------------------------------------//
        
        //-----------------------------------------------------------------------------------------------------------------//
        // Standard constructor.
        //-----------------------------------------------------------------------------------------------------------------//
        Vec2_f()
        {
            m_data[0] = 0.0f;
            m_data[1] = 0.0f;
        }

        Vec2_f(float x, float y)
        {
            m_data[0] = x;
            m_data[1] = y;
        }
        //-----------------------------------------------------------------------------------------------------------------//

        //-----------------------------------------------------------------------------------------------------------------//
        // Copy and move constructors.
        //-----------------------------------------------------------------------------------------------------------------//
        Vec2_f(const Vec2_f& other)
        {
            for(int i = 0; i < 2; i++)
            {
                m_data[i] = other.m_data[i];
            }
        }

        Vec2_f& operator=(const Vec2_f& other)
        {
            for(int i = 0; i < 2; i++)
            {
                m_data[i] = other.m_data[i];
            }
            return *this;
        }
        //-----------------------------------------------------------------------------------------------------------------//

        //-----------------------------------------------------------------------------------------------------------------//
        // Comparison operator overloads.
        //-----------------------------------------------------------------------------------------------------------------//
        bool operator==(const Vec2_f& other) const
        {
            for(int i = 0; i < 2; i++)
            {
                if(Utils::checkFloatEquals(m_data[i], other.m_data[i]) == false)
                {
                    return false;
                }
            }
            return true;
        }

        bool operator!=(const Vec2_f& other) const
        {
            for(int i = 0; i < 2; i++)
            {
                if(Utils::checkFloatEquals(m_data[i], other.m_data[i]) == true)
                {
                    return false;
                }
            }
            return true;
        }
        //-----------------------------------------------------------------------------------------------------------------//

        //-----------------------------------------------------------------------------------------------------------------//
        // Arithmetic operator overloads.
        //-----------------------------------------------------------------------------------------------------------------//
        Vec2_f operator+(const Vec2_f& rhs) const
        {
            return Vec2_f
            (
                m_data[0] + rhs.m_data[0],
                m_data[1] + rhs.m_data[1]
            );
        }

        Vec2_f operator-(const Vec2_f& rhs) const
        {
            return Vec2_f
            (
                m_data[0] - rhs.m_data[0],
                m_data[1] - rhs.m_data[1]
            );
        }

        Vec2_f operator*(const float scalar) const
        {
            return Vec2_f
            (
                m_data[0] * scalar,
                m_data[1] * scalar
            );
        }

        Vec2_f operator/(const float scalar) const
        {
            return Vec2_f
            (
                m_data[0] / scalar,
                m_data[1] / scalar
            );
        }
        //-----------------------------------------------------------------------------------------------------------------//

        //-----------------------------------------------------------------------------------------------------------------//
        // Single-Object Operations.
        //-----------------------------------------------------------------------------------------------------------------//
        inline float length()
        {
            float length = 0.0f;
            for(int i = 0; i < 2; i++)
            {
                length += (m_data[i] * m_data[i]);
            }
            length = sqrtf(length);

            return length;
        }

        inline void normalise()
        {
            float length = 0.0f;
            for(int i = 0; i < 2; i++)
            {
                length += (m_data[i] * m_data[i]);
            }
            length = sqrtf(length);

            if(length == 0.0f)
            {
                for(int i = 0; i < 2; i++)
                {
                    m_data[i] = 0.0f;
                }
                return;
            }

            for(int i = 0; i < 2; i++)
            {
                m_data[i] = m_data[i] / length;
            }   
        }
        //-----------------------------------------------------------------------------------------------------------------//

        //-----------------------------------------------------------------------------------------------------------------//
        // Visulisation.
        //-----------------------------------------------------------------------------------------------------------------//
        std::string toStringRow(int min_num_width, int num_decimals) const
        {
            return
            (
                std::string("[") +
                Utils::floatToString(m_data[0], min_num_width, num_decimals) + std::string(", ") +
                Utils::floatToString(m_data[1], min_num_width, num_decimals) +
                std::string("]")
            );
        }
        //-----------------------------------------------------------------------------------------------------------------//
    };
};
