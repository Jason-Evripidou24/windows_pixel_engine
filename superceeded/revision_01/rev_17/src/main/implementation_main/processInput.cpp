// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //
void processInput(Window& window, float delta_time)
{
    //---------------------------------------------------------------------------------------------------------------------//
    // Movement.
    //---------------------------------------------------------------------------------------------------------------------//
    float movement = g_camera_move_speed * delta_time;

    // Move camera along x
    if(window.m_input.isKeyDown('A') == true) { g_camera.moveRight(-movement); }
    if(window.m_input.isKeyDown('D') == true) { g_camera.moveRight(movement); }
    // Move camera along y
    if(window.m_input.isKeyDown('Q') == true) { g_camera.moveUp(movement); }
    if(window.m_input.isKeyDown('E') == true) { g_camera.moveUp(-movement); }
    // Move camera along z
    if(window.m_input.isKeyDown('W') == true) { g_camera.moveForward(movement); }
    if(window.m_input.isKeyDown('S') == true) { g_camera.moveForward(-movement); }
    //---------------------------------------------------------------------------------------------------------------------//

    //---------------------------------------------------------------------------------------------------------------------//
    // Wireframe and Filled mode.
    //---------------------------------------------------------------------------------------------------------------------//
    bool curr_0_key = window.m_input.isKeyDown('0');
    if( (curr_0_key == true) && (g_prev_0_key == false) )
    {
        g_draw_filled = !g_draw_filled;
    }
    g_prev_0_key = curr_0_key;
    //---------------------------------------------------------------------------------------------------------------------//

    //---------------------------------------------------------------------------------------------------------------------//
    // Movement speed.
    //---------------------------------------------------------------------------------------------------------------------//
    if(window.m_input.isKeyDown('1') == true)
    {
        g_camera_move_speed += 0.1f;
    }
    if(window.m_input.isKeyDown('2') == true)
    {
        g_camera_move_speed -= 0.1f;
        if(g_camera_move_speed <= 0.0f) { g_camera_move_speed = 0.0f; }
    }
    //---------------------------------------------------------------------------------------------------------------------//

    //---------------------------------------------------------------------------------------------------------------------//
    // Color mixing between vertex color and material color.
    //---------------------------------------------------------------------------------------------------------------------//
    bool curr_8_key = window.m_input.isKeyDown('8');
    if( (curr_8_key == true) && (g_prev_8_key == false) )
    {
        g_vertex_material_color_mix -= 0.1f;
        if(g_vertex_material_color_mix <= 0.0f) { g_vertex_material_color_mix = 0.0f; }
    }
    g_prev_8_key = curr_8_key;

    bool curr_9_key = window.m_input.isKeyDown('9');
    if( (curr_9_key == true) && (g_prev_9_key == false) )
    {
        g_vertex_material_color_mix += 0.1f;
        if(g_vertex_material_color_mix >= 1.0f) { g_vertex_material_color_mix = 1.0f; }
    }
    g_prev_9_key = curr_9_key;
    //---------------------------------------------------------------------------------------------------------------------//

    //---------------------------------------------------------------------------------------------------------------------//
    // Mouse.
    //---------------------------------------------------------------------------------------------------------------------//
    float curr_mouse_pos_x = (float)window.m_input.m_mouse_x;
    float curr_mouse_pos_y = (float)window.m_input.m_mouse_y;

    if(window.m_input.isMouseDown(0) == true)
    {
        float mouse_dx = g_mouse_pos_x - curr_mouse_pos_x;
        float mouse_dy = g_mouse_pos_y - curr_mouse_pos_y;

        g_camera.lookRight(mouse_dx * g_camera_look_speed);
        g_camera.lookUp(mouse_dy * g_camera_look_speed);
    }
    g_mouse_pos_x = curr_mouse_pos_x;
    g_mouse_pos_y = curr_mouse_pos_y;
    //---------------------------------------------------------------------------------------------------------------------//
}
