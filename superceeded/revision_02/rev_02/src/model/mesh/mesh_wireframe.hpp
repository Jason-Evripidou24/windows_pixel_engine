// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //
struct MeshWireframe
{
    Math::Geometry::Wireframe m_wireframe;
    std::string m_wireframe_material_name;

    //---------------------------------------------------------------------------------------------------------------------//
    // Constructors.
    //---------------------------------------------------------------------------------------------------------------------//
    MeshWireframe()
    {
        m_wireframe.clear();
        m_wireframe_material_name.clear();
    }
    //---------------------------------------------------------------------------------------------------------------------//

    //---------------------------------------------------------------------------------------------------------------------//
    // Copy constructors.
    //---------------------------------------------------------------------------------------------------------------------//
    MeshWireframe(const MeshWireframe& other)
    {
        m_wireframe = other.m_wireframe;
        m_wireframe_material_name = other.m_wireframe_material_name;
    }

    MeshWireframe& operator=(const MeshWireframe& other)
    {
        if(this != &other)
        {
            m_wireframe = other.m_wireframe;
            m_wireframe_material_name = other.m_wireframe_material_name;
        }
        return *this;
    }

    MeshWireframe(MeshWireframe&& other) noexcept
    {
        m_wireframe = std::move(other.m_wireframe);
        m_wireframe_material_name = std::move(other.m_wireframe_material_name);
    }

    MeshWireframe& operator=(MeshWireframe&& other) noexcept
    {
        if(this != &other)
        {
            m_wireframe = std::move(other.m_wireframe);
            m_wireframe_material_name = std::move(other.m_wireframe_material_name);
        }
        return *this;
    }
    //---------------------------------------------------------------------------------------------------------------------//
};
