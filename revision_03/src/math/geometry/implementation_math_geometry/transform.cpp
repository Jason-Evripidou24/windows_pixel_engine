// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //
void Math::Geometry::transformVertex
(
    Math::Geometry::Vertex& output,
    const Math::Geometry::Vertex& vertex,
    const Math::Core::Mat4_f& matrix
)
{
    output = vertex;
    output.m_position = matrix * vertex.m_position;
}
// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //


// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //
void Math::Geometry::transformPolygon
(
    Math::Geometry::Polygon& output,
    const Math::Geometry::Polygon& polygon,
    const Math::Core::Mat4_f& matrix
)
{
    output.resize(polygon.m_num_vertices);

    for(size_t i = 0; i < polygon.m_num_vertices; i++)
    {
        Math::Geometry::transformVertex(output.m_vertices[i], polygon.m_vertices[i], matrix);
    }
}
// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //


// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //
void Math::Geometry::transformWireframe
(
    Math::Geometry::Wireframe& output,
    const Math::Geometry::Wireframe& wireframe,
    const Math::Core::Mat4_f& matrix
)
{
    output.resize(wireframe.m_num_polygons);

    for(size_t i = 0; i < wireframe.m_num_polygons; i++)
    {
        Math::Geometry::transformPolygon(output.m_polygons[i], wireframe.m_polygons[i], matrix);
    }
}
// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //


// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //
void Math::Geometry::transformMultiWireframe
(
    Math::Geometry::MultiWireframe& output,
    const Math::Geometry::MultiWireframe& multi_wireframe,
    const Math::Core::Mat4_f& matrix
)
{
    output.resize(multi_wireframe.m_num_wireframes);

    for(size_t i = 0; i < multi_wireframe.m_num_wireframes; i++)
    {
        Math::Geometry::transformWireframe(output.m_wireframes[i], multi_wireframe.m_wireframes[i], matrix);
    }
}
