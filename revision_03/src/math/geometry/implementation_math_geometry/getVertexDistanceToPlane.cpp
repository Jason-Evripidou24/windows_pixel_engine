// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //
// Vertex is in Homogenous Space.
float Math::Geometry::getVertexDistanceToPlaneMinX(const Math::Geometry::Vertex& v)
{
    // x + w
    return v.m_position.m_data[0] + v.m_position.m_data[3];
}
