// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //
// Vertex is in Homogenous Space.
bool Math::Geometry::checkVertexInsidePlaneMinX(const Math::Geometry::Vertex& v)
{
    // (x >= -w) => (x + w >= 0)
    return Math::Geometry::getVertexDistanceToPlaneMinX(v) >= 0.0f;
}
