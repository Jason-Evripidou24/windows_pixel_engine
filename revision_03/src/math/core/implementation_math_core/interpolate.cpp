// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //
/*
-   t must be within 0.0f <= t <= 1.0f
*/
void Math::Core::interpolateVec3f(Math::Core::Vec3_f& output, const Math::Core::Vec3_f& start, const Math::Core::Vec3_f& end, float t)
{
    //---------------------------------------------------------------------------------------------------------------------//
    if(t <= 0.0f) { t = 0.0f; }
    if(t >= 1.0f) { t = 1.0f; }
    //---------------------------------------------------------------------------------------------------------------------//
    
    for(int i = 0; i < 3; i++)
    {
        output.m_data[i] = Math::Core::interpolateFloat(start.m_data[i], end.m_data[i], t);
    }
}
