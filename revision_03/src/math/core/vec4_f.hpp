namespace Math
{
    namespace Core
    {
        struct Vec4_f
        {
            //-------------------------------------------------------------------------------------------------------------//
            static constexpr size_t m_data_size = 4;
            float m_data[m_data_size];
            //-------------------------------------------------------------------------------------------------------------//
            
            //-------------------------------------------------------------------------------------------------------------//
            // Standard constructor.
            //-------------------------------------------------------------------------------------------------------------//
            Vec4_f()
            {
                m_data[0] = 0.0f;
                m_data[1] = 0.0f;
                m_data[2] = 0.0f;
                m_data[3] = 0.0f;
            }

            Vec4_f(float x, float y, float z, float w)
            {
                m_data[0] = x;
                m_data[1] = y;
                m_data[2] = z;
                m_data[3] = w;
            }
            //-------------------------------------------------------------------------------------------------------------//

            //-------------------------------------------------------------------------------------------------------------//
            // Copy and Move constructors.
            //-------------------------------------------------------------------------------------------------------------//
            Vec4_f(const Vec4_f& other)
            {
                for(size_t i = 0; i < m_data_size; i++)
                {
                    m_data[i] = other.m_data[i];
                }
            }

            Vec4_f& operator=(const Vec4_f& other)
            {
                if(this != &other)
                {
                    for(size_t i = 0; i < m_data_size; i++)
                    {
                        m_data[i] = other.m_data[i];
                    }
                }
                return *this;
            }

            Vec4_f(Vec4_f&& other) noexcept
            {
                for(size_t i = 0; i < m_data_size; i++)
                {
                    m_data[i] = other.m_data[i];
                }
            }

            Vec4_f& operator=(Vec4_f&& other) noexcept
            {
                if(this != &other)
                {
                    for(size_t i = 0; i < m_data_size; i++)
                    {
                        m_data[i] = other.m_data[i];
                    }
                }
                return *this;
            }
            //-------------------------------------------------------------------------------------------------------------//

            //-------------------------------------------------------------------------------------------------------------//
            // Comparison operator overloads.
            //-------------------------------------------------------------------------------------------------------------//
            bool operator==(const Vec4_f& other) const
            {
                for(size_t i = 0; i < m_data_size; i++)
                {
                    if(Utils::checkFloatEquals(m_data[i], other.m_data[i]) == false)
                    {
                        return false;
                    }
                }
                return true;
            }

            bool operator!=(const Vec4_f& other) const
            {
                for(size_t i = 0; i < m_data_size; i++)
                {
                    if(Utils::checkFloatEquals(m_data[i], other.m_data[i]) == false)
                    {
                        return true;
                    }
                }
                return false;
            }
            //-------------------------------------------------------------------------------------------------------------//

            //-------------------------------------------------------------------------------------------------------------//
            // Arithmetic operator overloads.
            //-------------------------------------------------------------------------------------------------------------//
            Vec4_f operator+(const Vec4_f& rhs) const
            {
                Vec4_f result;
                for(size_t i = 0; i < m_data_size; i++)
                {
                    result.m_data[i] = m_data[i] + rhs.m_data[i];
                }
                return result;
            }

            Vec4_f operator-(const Vec4_f& rhs) const
            {
                Vec4_f result;
                for(size_t i = 0; i < m_data_size; i++)
                {
                    result.m_data[i] = m_data[i] - rhs.m_data[i];
                }
                return result;
            }

            Vec4_f operator*(const float scalar) const
            {
                Vec4_f result;
                for(size_t i = 0; i < m_data_size; i++)
                {
                    result.m_data[i] = m_data[i] * scalar;
                }
                return result;
            }

            Vec4_f operator/(const float scalar) const
            {
                Vec4_f result;
                for(size_t i = 0; i < m_data_size; i++)
                {
                    result.m_data[i] = m_data[i] / scalar;
                }
                return result;
            }
            //-------------------------------------------------------------------------------------------------------------//

            //-------------------------------------------------------------------------------------------------------------//
            // Single-Object Operations.
            //-------------------------------------------------------------------------------------------------------------//
            inline float length()
            {
                float length = 0.0f;
                for(size_t i = 0; i < m_data_size; i++)
                {
                    length += (m_data[i] * m_data[i]);
                }
                length = sqrtf(length);

                return length;
            }

            inline void normalise()
            {
                float length = 0.0f;
                for(size_t i = 0; i < m_data_size; i++)
                {
                    length += (m_data[i] * m_data[i]);
                }
                length = sqrtf(length);

                if(length == 0.0f)
                {
                    for(size_t i = 0; i < m_data_size; i++)
                    {
                        m_data[i] = 0.0f;
                    }
                    return;
                }

                for(size_t i = 0; i < m_data_size; i++)
                {
                    m_data[i] = m_data[i] / length;
                }   
            }
            //-------------------------------------------------------------------------------------------------------------//

            //-------------------------------------------------------------------------------------------------------------//
            // Visulisation.
            //-------------------------------------------------------------------------------------------------------------//
            std::string toStringRow(int min_num_width, int num_decimals) const
            {
                return
                (
                    std::string("[") +
                    Utils::floatToString(m_data[0], min_num_width, num_decimals) + std::string(", ") +
                    Utils::floatToString(m_data[1], min_num_width, num_decimals) + std::string(", ") +
                    Utils::floatToString(m_data[2], min_num_width, num_decimals) + std::string(", ") +
                    Utils::floatToString(m_data[3], min_num_width, num_decimals) +
                    std::string("]")
                );
            }

            std::string toStringCol(int min_num_width, int num_decimals) const
            {
                return
                (
                    std::string("|") +
                    Utils::floatToString(m_data[0], min_num_width, num_decimals) +
                    std::string("|") +
                    std::string("\n") +
                    std::string("|") +
                    Utils::floatToString(m_data[1], min_num_width, num_decimals) +
                    std::string("|") +
                    std::string("\n") +
                    std::string("|") +
                    Utils::floatToString(m_data[2], min_num_width, num_decimals) +
                    std::string("|") +
                    std::string("\n") +
                    std::string("|") +
                    Utils::floatToString(m_data[3], min_num_width, num_decimals) +
                    std::string("|")
                );
            }
            //-------------------------------------------------------------------------------------------------------------//
        };
    };
};
