Math::Core::Mat4_f Camera::calcProjectionMatrix(const float aspect_ratio) const
{
    Math::Core::Mat4_f new_mat;
    new_mat.perspective(m_fov_rads, aspect_ratio, m_near_plane, m_far_plane);
    return new_mat;
}
