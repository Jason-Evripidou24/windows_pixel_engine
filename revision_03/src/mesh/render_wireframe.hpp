//-------------------------------------------------------------------------------------------------------------------------//
// Standard library.
//-------------------------------------------------------------------------------------------------------------------------//
#include <string>
//-------------------------------------------------------------------------------------------------------------------------//

//-------------------------------------------------------------------------------------------------------------------------//
// Third party.
//-------------------------------------------------------------------------------------------------------------------------//
//-------------------------------------------------------------------------------------------------------------------------//

//-------------------------------------------------------------------------------------------------------------------------//
// Internal.
//-------------------------------------------------------------------------------------------------------------------------//
#include "../math/geometry/wireframe.hpp"
//-------------------------------------------------------------------------------------------------------------------------//
// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //


// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //
struct RenderWireframe
{
    Math::Geometry::Wireframe m_wireframe;
    std::string m_wireframe_material_name;

    //---------------------------------------------------------------------------------------------------------------------//
    // Constructors.
    //---------------------------------------------------------------------------------------------------------------------//
    RenderWireframe()
    {
        m_wireframe.clear();
        m_wireframe_material_name.clear();
    }
    //---------------------------------------------------------------------------------------------------------------------//

    //---------------------------------------------------------------------------------------------------------------------//
    // Copy constructors.
    //---------------------------------------------------------------------------------------------------------------------//
    RenderWireframe(const RenderWireframe& other)
    {
        m_wireframe = other.m_wireframe;
        m_wireframe_material_name = other.m_wireframe_material_name;
    }

    RenderWireframe& operator=(const RenderWireframe& other)
    {
        if(this != &other)
        {
            m_wireframe = other.m_wireframe;
            m_wireframe_material_name = other.m_wireframe_material_name;
        }
        return *this;
    }

    RenderWireframe(RenderWireframe&& other) noexcept
    {
        m_wireframe = std::move(other.m_wireframe);
        m_wireframe_material_name = std::move(other.m_wireframe_material_name);
    }

    RenderWireframe& operator=(RenderWireframe&& other) noexcept
    {
        if(this != &other)
        {
            m_wireframe = std::move(other.m_wireframe);
            m_wireframe_material_name = std::move(other.m_wireframe_material_name);
        }
        return *this;
    }
    //---------------------------------------------------------------------------------------------------------------------//
};
