// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //
struct Mesh
{
    //---------------------------------------------------------------------------------------------------------------------//
    // Identifiers.
    //---------------------------------------------------------------------------------------------------------------------//
    int m_mesh_id;
    std::string m_mesh_name;
    //---------------------------------------------------------------------------------------------------------------------//

    //---------------------------------------------------------------------------------------------------------------------//
    // Drawing/Rendering information.
    //---------------------------------------------------------------------------------------------------------------------//
    MaterialLibrary m_material_library;
    std::vector<RenderWireframe> m_render_wireframes;
    //---------------------------------------------------------------------------------------------------------------------//

    //---------------------------------------------------------------------------------------------------------------------//
    // Collision and Selection detection.
    //---------------------------------------------------------------------------------------------------------------------//
    Math::Geometry::MultiWireframe m_hitbox;
    //---------------------------------------------------------------------------------------------------------------------//

    //---------------------------------------------------------------------------------------------------------------------//
    Mesh()
    {
        m_mesh_id = -1;
        m_mesh_name.clear();
        m_material_library.clear();
        m_render_wireframes.clear();
        m_hitbox.clear();
    }
    Mesh(int mesh_id, const std::string& mesh_name)
    {
        m_mesh_id = mesh_id;
        m_mesh_name = mesh_name;
        m_material_library.clear();
        m_render_wireframes.clear();
        m_hitbox.clear();
    }
    ~Mesh()
    {
        m_mesh_id = -1;
        m_mesh_name.clear();
        m_material_library.clear();
        m_render_wireframes.clear();
        m_hitbox.clear();
    }
    //---------------------------------------------------------------------------------------------------------------------//

    //---------------------------------------------------------------------------------------------------------------------//
    void loadMesh
    (
        const std::string& folder,
        const std::string& render_wireframe_file_name,
        const std::string& material_library_file_name,
        const std::string& hitbox_file_name
    )
    {
        m_render_wireframes = ObjFileParser::loadRenderWireframes(folder, render_wireframe_file_name);
        m_material_library = MtlFileParser::loadMaterialLibrary(folder, material_library_file_name);
        m_hitbox = ObjFileParser::loadMultiWireframe(folder, hitbox_file_name);
    }
    //---------------------------------------------------------------------------------------------------------------------//

    //---------------------------------------------------------------------------------------------------------------------//
    inline std::string toString()
    {
        std::string output = std::string("");
        output += std::string("MESH ID  : ") + std::to_string(m_mesh_id) + std::string("\n");
        output += std::string("MESH NAME: ") + m_mesh_name;
        return output;
    }
    //---------------------------------------------------------------------------------------------------------------------//
};
