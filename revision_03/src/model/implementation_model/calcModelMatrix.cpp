Math::Core::Mat4_f Model::calcModelMatrix() const
{
    Math::Core::Mat4_f translate;
    translate.translation
    (
        m_position.m_data[0],
        m_position.m_data[1],
        m_position.m_data[2]
    );

    Math::Core::Mat4_f scale;
    scale.scale
    (
        m_scale.m_data[0],
        m_scale.m_data[1],
        m_scale.m_data[2]
    );

    Math::Core::Mat4_f rotate;
    rotate.rotation
    (
        m_rotate_axis.m_data[0],
        m_rotate_axis.m_data[1],
        m_rotate_axis.m_data[2],
        m_rotate_rad
    );
    
    Math::Core::Mat4_f model = translate * rotate * scale;

    return model;
}
