// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //
struct MaterialPolygon
{
    Math::Geometry::Polygon m_polygon;
    Material*               m_material;

    //---------------------------------------------------------------------------------------------------------------------//
    // Constructors.
    //---------------------------------------------------------------------------------------------------------------------//
    MaterialPolygon()
    {
        m_polygon.clear();
        m_material = nullptr;
    }
    //---------------------------------------------------------------------------------------------------------------------//

    //---------------------------------------------------------------------------------------------------------------------//
    // Copy constructors.
    //---------------------------------------------------------------------------------------------------------------------//
    MaterialPolygon(const MaterialPolygon& other)
    {
        m_polygon = other.m_polygon;
        m_material = other.m_material;
    }

    MaterialPolygon& operator=(const MaterialPolygon& other)
    {
        if(this != &other)
        {
            m_polygon = other.m_polygon;
            m_material = other.m_material;
        }
        return *this;
    }

    MaterialPolygon(MaterialPolygon&& other) noexcept
    {
        m_polygon = std::move(other.m_polygon);
        m_material = other.m_material;
    }

    MaterialPolygon& operator=(MaterialPolygon&& other) noexcept
    {
        if(this != &other)
        {
            m_polygon = std::move(other.m_polygon);
            m_material = other.m_material;
        }
        return *this;
    }
    //---------------------------------------------------------------------------------------------------------------------//
};
