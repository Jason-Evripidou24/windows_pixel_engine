namespace Math
{
    namespace Geometry
    {
        struct Vertex
        {
            //-------------------------------------------------------------------------------------------------------------//
            Math::Core::Vec4_f m_position  ;
            Math::Core::Vec2_f m_tex_coords;
            Math::Core::Vec3_f m_normal    ;
            Math::Core::Vec4_f m_color     ; // a-r-g-b
            //-------------------------------------------------------------------------------------------------------------//

            //-------------------------------------------------------------------------------------------------------------//
            // Standard constructor.
            //-------------------------------------------------------------------------------------------------------------//
            Vertex()
            {
                m_position   = Math::Core::Vec4_f();
                m_tex_coords = Math::Core::Vec2_f();
                m_normal     = Math::Core::Vec3_f();
                m_color      = Math::Core::Vec4_f(); // Black.
            }

            Vertex
            (
                const Math::Core::Vec4_f& position  ,
                const Math::Core::Vec2_f& tex_coords,
                const Math::Core::Vec3_f& normal    ,
                const Math::Core::Vec4_f& color
            )
            {
                m_position   = position  ;
                m_tex_coords = tex_coords;
                m_normal     = normal    ;
                m_color      = color     ;
            }
            //-------------------------------------------------------------------------------------------------------------//

            //-------------------------------------------------------------------------------------------------------------//
            // Copy and Move constructors.
            //-------------------------------------------------------------------------------------------------------------//
            Vertex(const Vertex& other)
            {
                m_position = other.m_position    ;
                m_tex_coords = other.m_tex_coords;
                m_normal = other.m_normal        ;
                m_color = other.m_color          ;
            }

            Vertex& operator=(const Vertex& other)
            {
                if(this != &other)
                {
                    m_position = other.m_position    ;
                    m_tex_coords = other.m_tex_coords;
                    m_normal = other.m_normal        ;
                    m_color = other.m_color          ;
                }
                return *this;
            }

            Vertex(Vertex&& other) noexcept
            {
                m_position   = std::move(other.m_position)  ;
                m_tex_coords = std::move(other.m_tex_coords);
                m_normal     = std::move(other.m_normal)    ;
                m_color      = std::move(other.m_color)     ;
            }

            Vertex& operator=(Vertex&& other) noexcept
            {
                if(this != &other)
                {
                    m_position   = std::move(other.m_position)  ;
                    m_tex_coords = std::move(other.m_tex_coords);
                    m_normal     = std::move(other.m_normal)    ;
                    m_color      = std::move(other.m_color)     ;
                }
                return *this;
            }
            //-------------------------------------------------------------------------------------------------------------//

            //-------------------------------------------------------------------------------------------------------------//
            // Single-Object Operations.
            //-------------------------------------------------------------------------------------------------------------//
            inline void perspectiveDivide()
            {
                float w = m_position.m_data[3];
                if(w <= 0.0f)
                {
                    m_position.m_data[0] = 0.0f;
                    m_position.m_data[1] = 0.0f;
                    m_position.m_data[2] = 0.0f;
                    m_position.m_data[3] = 0.0f;
                }
                else
                {
                    float inv_w = 1.0f / w;

                    m_position.m_data[0] = m_position.m_data[0] * inv_w;
                    m_position.m_data[1] = m_position.m_data[1] * inv_w;
                    m_position.m_data[2] = m_position.m_data[2] * inv_w;
                    m_position.m_data[3] = m_position.m_data[3]        ;
                }
            }
            //-------------------------------------------------------------------------------------------------------------//

            //-------------------------------------------------------------------------------------------------------------//
            // Visulisation.
            //-------------------------------------------------------------------------------------------------------------//
            std::string toString(int min_num_width, int num_decimals) const
            {
                return
                (
                    std::string("VERTEX INFO:") + std::string("\n") +
                    std::string("POSITION:   ") + m_position.toStringRow(min_num_width, num_decimals) + std::string("\n") +
                    std::string("TEX COORDS: ") + m_tex_coords.toStringRow(min_num_width, num_decimals) + std::string("\n") +
                    std::string("NORMAL:     ") + m_normal.toStringRow(min_num_width, num_decimals) + std::string("\n") +
                    std::string("COLOR:      ") + m_color.toStringRow(min_num_width, num_decimals)
                );
            }
            //-------------------------------------------------------------------------------------------------------------//
        };
    };
};
