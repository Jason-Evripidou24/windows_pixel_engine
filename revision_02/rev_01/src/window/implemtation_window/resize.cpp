// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //
void Window::resize(int width, int height)
{
    //---------------------------------------------------------------------------------------------------------------------//
    if( ( (width == m_width) && (height == m_height) ) || (width <= 0) || (height <= 0) ) 
    {
        return;
    }
    //---------------------------------------------------------------------------------------------------------------------//

    m_width  = width;
    m_height = height;

    m_backbuffer.resize(m_width / m_pixel_size, m_height / m_pixel_size);
}
// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //


// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //
void Window::resizePixel(int pixel_size)
{
    //---------------------------------------------------------------------------------------------------------------------//
    if( (pixel_size == m_pixel_size) || (pixel_size <= 0) ) { return; }
    //---------------------------------------------------------------------------------------------------------------------//

    m_pixel_size = pixel_size;

    m_backbuffer.resize(m_width / m_pixel_size, m_height / m_pixel_size);
}
