/*
-   Renderer pipeline:
    1.  Local/Object Space (Vec3, Vec4 with 1.0f as the homogenious coordinate)
    |   Model Matrix
    2.  World Space (Vec4)
    |   View Matrix
    3.  View Space
    |   Projection Matrix
    4.  Clip Space (Vec4)
    |   Homogeneous Clipping
    |   Perspective Divide
    5.  Normalized Device Coordinates (NDC)
    |   Viewport Transform
    6.  Screen Space
    |   Rasterization, Depth Test, Framebuffer


-   draw... functions are responsible for rendering triangles that are in clip space.
*/
struct Renderer
{
    //---------------------------------------------------------------------------------------------------------------------//
    // Constructor and destructor.
    //---------------------------------------------------------------------------------------------------------------------//
    Renderer() = default;
    ~Renderer() = default;
    //---------------------------------------------------------------------------------------------------------------------//

    //---------------------------------------------------------------------------------------------------------------------//
    // Draw functions. Triangles here are in clip space.
    //---------------------------------------------------------------------------------------------------------------------//
    void drawTriangle
    (
        Backbuffer& target,
        float       v0_x,
        float       v0_y,
        float       v0_z,
        uint32_t    v0_color,
        float       v1_x,
        float       v1_y,
        float       v1_z,
        uint32_t    v1_color,
        float       v2_x,
        float       v2_y,
        float       v2_z,
        uint32_t    v2_color
    );
    //---------------------------------------------------------------------------------------------------------------------//
};
