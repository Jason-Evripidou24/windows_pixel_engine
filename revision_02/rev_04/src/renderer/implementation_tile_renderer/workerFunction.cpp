void TileRenderer::workerFunction()
{
    while(m_running.load() == true)
    {
        TileRendererJob tile_renderer_job;

        //-----------------------------------------------------------------------------------------------------------------//
        std::unique_lock<std::mutex> jobs_lock(m_jobs_mutex);

        m_jobs_condition_variable.wait
        (
            jobs_lock,
            [&]
            {
                return (m_jobs.empty() == false) || (m_running.load() == false);
            }
        );

        if(m_running.load() == false) { break; }

        tile_renderer_job = m_jobs.front();
        m_jobs.pop();

        jobs_lock.unlock();
        //-----------------------------------------------------------------------------------------------------------------//

        this->fillTriangle
        (
            tile_renderer_job.m_v0,
            tile_renderer_job.m_v1,
            tile_renderer_job.m_v2,
            tile_renderer_job.m_material,
            tile_renderer_job.m_color_mix
        );

        //-----------------------------------------------------------------------------------------------------------------//
        std::unique_lock<std::mutex> extern_jobs_pending_lock(*(tile_renderer_job.m_extern_pending_jobs_mutex));

        (tile_renderer_job.m_extern_pending_jobs)->fetch_sub(1);

        if((tile_renderer_job.m_extern_pending_jobs)->load() == 0)
        {
            (tile_renderer_job.m_extern_pending_jobs_condition_variable)->notify_all();
        }

        extern_jobs_pending_lock.unlock();
        //-----------------------------------------------------------------------------------------------------------------//
    }
}
