void TileRenderer::submitJob
(
    const Math::Triangle* triangle,
    const Material* material,
    float color_mix
)
{
    std::unique_lock<std::mutex> lock(m_jobs_mutex);
    
    if( (m_running.load() == false) || (triangle == nullptr) || (material == nullptr) )
    {
        return;
    }

    m_jobs.push(TileRendererJob(triangle, material, color_mix));

    lock.unlock();
    m_jobs_condition_variable.notify_all();
}
