void TileRenderer::parentRequestDrawTriangle
(
    Math::Triangle*   triangle,
    Material*         material,
    bool              draw_filled,
    float             color_mix,
    bool*             parent_job_complete
)
{
    std::unique_lock<std::mutex> lock(m_object_mutex);
    
    if( (m_running == false) || (triangle == nullptr) || (material == nullptr) ) { return; }

    m_tile_renderer_job.m_triangle = triangle;
    m_tile_renderer_job.m_material = material;
    m_tile_renderer_job.m_draw_filled = draw_filled;
    m_tile_renderer_job.m_color_mix = color_mix;
    m_tile_renderer_job.m_parent_job_complete = parent_job_complete;

    m_has_job = true;

    lock.unlock();
    m_object_condition_variable.notify_all();
}
