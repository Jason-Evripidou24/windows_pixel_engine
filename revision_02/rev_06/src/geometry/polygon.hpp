namespace Geometry
{
    struct Polygon
    {
        size_t m_num_vertices;
        std::vector<Math::Vertex> m_vertices;

        Polygon()
        {
            m_num_vertices = 0;
            m_vertices = std::vector<Math::Vertex>();
        }

        //-----------------------------------------------------------------------------------------------------------------//
        // Copy constructors.
        //-----------------------------------------------------------------------------------------------------------------//
        Polygon(const Polygon& other)
        {
            m_num_vertices = other.m_num_vertices;
            m_vertices = other.m_vertices;
        }

        Polygon& operator=(const Polygon& other)
        {
            m_num_vertices = other.m_num_vertices;
            m_vertices = other.m_vertices;
            return *this;
        }
        //-----------------------------------------------------------------------------------------------------------------//

        inline void clear()
        {
            m_num_vertices = 0;
        }

        inline void resize(size_t size)
        {
            m_num_vertices = size;
            if(m_vertices.size() < size)
            {
                m_vertices.resize(size);
            }
        }

        inline void addVertex(const Math::Vertex& vertex)
        {
            if(m_num_vertices < m_vertices.size())
            {
                m_vertices[m_num_vertices] = vertex;
            }
            else
            {
                m_vertices.push_back(vertex);
            }
            m_num_vertices++;
        }
    };
};
