struct Model
{
    //---------------------------------------------------------------------------------------------------------------------//
    int m_model_id;
    std::string m_model_name;

    Mesh* m_mesh;

    Math::Vec3_f m_position;
    Math::Vec3_f m_scale;
    float m_rotate_rad;
    Math::Vec3_f m_rotate_axis;
    //---------------------------------------------------------------------------------------------------------------------//

    //---------------------------------------------------------------------------------------------------------------------//
    Model()
    {
        m_mesh = nullptr;
        m_position = Math::Vec3_f();
        m_scale = Math::Vec3_f();
        m_rotate_rad = 0.0f;
        m_rotate_axis = Math::Vec3_f();
    }

    Model(int model_id, const std::string& model_name, Mesh* mesh)
    {
        m_model_id = model_id;
        m_model_name = model_name;

        m_mesh = mesh;
        m_position = Math::Vec3_f();
        m_scale = Math::Vec3_f();
        m_rotate_rad = 0.0f;
        m_rotate_axis = Math::Vec3_f();
    }
    //---------------------------------------------------------------------------------------------------------------------//

    //---------------------------------------------------------------------------------------------------------------------//
    Math::Mat4_f calcModelMatrix() const;

    inline void moveModel(const float x_axis, const float y_axis, const float z_axis, const float offset)
    {
        Math::Vec3_f move(x_axis, y_axis, z_axis);
        move = move * offset;
        m_position = m_position + move;
    }

    void renderModel(Renderer& renderer, const Math::Mat4_f& projection_view_matrix, bool draw_filled, float color_mix);
    //---------------------------------------------------------------------------------------------------------------------//

    //---------------------------------------------------------------------------------------------------------------------//
    inline std::string toString()
    {
        std::string output = std::string("");
        output += std::string("MODEL ID  : ") + std::to_string(m_model_id) + std::string("\n");
        output += std::string("MODEL NAME: ") + m_model_name + std::string("\n");
        
        if(m_mesh == nullptr)
        {
            output += std::string("MODEL HAS NO MESH!");
        }
        else
        {
            output += std::string("MODEL MESH DETAILS:") + std::string("\n") + m_mesh->toString();
        }

        return output;
    }
    //---------------------------------------------------------------------------------------------------------------------//
};
