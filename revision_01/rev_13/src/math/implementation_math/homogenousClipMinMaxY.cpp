std::vector<Math::Triangle> Math::clipAgainstPlaneMinMaxY(const Math::Triangle& triangle)
{
    std::vector<Math::Triangle> traingles_clipped_min_y = Math::clipAgainstPlaneMinY(triangle);

    std::vector<Math::Triangle> traingles_clipped_min_max_y;
    traingles_clipped_min_max_y.reserve(4); // 2 triangles can become 4.

    for(const Math::Triangle& traingle_clipped_min_y : traingles_clipped_min_y)
    {
        std::vector<Math::Triangle> clipped = Math::clipAgainstPlaneMaxY(traingle_clipped_min_y);
        traingles_clipped_min_max_y.insert(traingles_clipped_min_max_y.end(), clipped.begin(), clipped.end());
    }

    return traingles_clipped_min_max_y;
}
